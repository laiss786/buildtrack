// js/reports.js — BuildTrack Weekly Site Report Generator
// ─────────────────────────────────────────────────────────────
// Ported from MERN Reports.js — generates a structured weekly
// site report entirely from local Firestore data (no AI/API call).
// Called from dashboard-patch.js when the Reports section opens.
// ─────────────────────────────────────────────────────────────

import { db } from "./firebase.js";
import {
  collection, getDocs, query, where, orderBy, limit
} from "https://www.gstatic.com/firebasejs/10.7.1/firebase-firestore.js";

// ── Helpers ───────────────────────────────────────────────────
const fmt = n => "₹" + Number(n || 0).toLocaleString("en-IN");

function userCol(uid, name) {
  return collection(db, "users", uid, name);
}

// ── Build the plain-text report string (ported 1:1 from MERN) ─
function generateReportText({
  startStr, weekEnd, projFilter,
  logs, labourers, att, expenses, issues,
  present, totalAtt, pct, labourCost, totalExp
}) {
  const catTotals = {};
  expenses.forEach(e => {
    catTotals[e.category] = (catTotals[e.category] || 0) + (e.amount || 0);
  });
  const catLines = Object.entries(catTotals)
    .map(([cat, amt]) => `   • ${cat}: ${fmt(amt)}`)
    .join("\n");

  const topWorkers = labourers.slice(0, 5).map(l => {
    const labId = l.id || l._id || "";
    const days = att.filter(a => a.labourerId === labId && a.status === "present").length;
    return `   • ${l.name} (${l.role || "Worker"}) — ${days} days present`;
  }).join("\n");

  const issueLines = issues.slice(0, 5)
    .map(i => `   • [${(i.severity || "medium").toUpperCase()}] ${i.title} — ${i.projectName || i.project || "General"}`)
    .join("\n") || "   • No open issues.";

  const logLines = logs.slice(0, 5)
    .map(l => `   • [${l.date}] ${l.project || "General"}: ${l.description}`)
    .join("\n") || "   • No journal entries this week.";

  const absent = totalAtt - present;
  const genDate = new Date().toLocaleDateString("en-IN", {
    day: "numeric", month: "long", year: "numeric"
  });

  return `════════════════════════════════════════════════
BUILDTRACK — WEEKLY SITE REPORT
════════════════════════════════════════════════
Period      : ${startStr} to ${weekEnd}
Project     : ${projFilter || "All Projects"}
Generated   : ${genDate}
════════════════════════════════════════════════

1. WEEKLY SUMMARY
─────────────────
This report covers site activity for the week ending ${weekEnd}.
A total of ${logs.length} journal ${logs.length === 1 ? "entry was" : "entries were"} recorded across active projects.
Labour attendance stood at ${pct}% with ${present} workers present out of ${totalAtt} recorded.
Total weekly expenditure amounts to ${fmt(totalExp)}, including labour costs of ${fmt(labourCost)}.
${issues.length > 0
  ? `There ${issues.length === 1 ? "is" : "are"} currently ${issues.length} open site ${issues.length === 1 ? "issue" : "issues"} requiring attention.`
  : "No open site issues this week."}

2. WORK PROGRESS
─────────────────
${logLines}
${logs.length > 5 ? `   ... and ${logs.length - 5} more entries.` : ""}

3. LABOUR & ATTENDANCE
───────────────────────
Total Records    : ${totalAtt}
Present          : ${present} (${pct}%)
Absent           : ${absent}
Total Labour Cost: ${fmt(labourCost)}

Top Workers This Week:
${topWorkers || "   • No worker data available."}

4. FINANCIAL SNAPSHOT
──────────────────────
Total Weekly Spend : ${fmt(totalExp)}
Labour Cost        : ${fmt(labourCost)}
Other Expenses     : ${fmt(Math.max(0, totalExp - labourCost))}

Breakdown by Category:
${catLines || "   • No expenses recorded this week."}

5. ISSUES & RECOMMENDATIONS
─────────────────────────────
Open Issues (${issues.length}):
${issueLines}

Recommendations:
${pct < 70
  ? "   ⚠ Attendance is below 70% — investigate absenteeism and ensure adequate staffing.\n"
  : "   ✓ Attendance is satisfactory.\n"}${issues.filter(i => i.severity === "high").length > 0
  ? `   ⚠ ${issues.filter(i => i.severity === "high").length} high-severity ${issues.filter(i => i.severity === "high").length === 1 ? "issue requires" : "issues require"} immediate attention.\n`
  : "   ✓ No high-severity issues open.\n"}${logs.length === 0
  ? "   ⚠ No journal entries this week — ensure site supervisors log daily progress.\n"
  : "   ✓ Site journal entries are up to date.\n"}
ACTION PLAN FOR NEXT WEEK:
   → Maintain attendance above 80%
   → Resolve all open high-severity issues
   → Ensure daily journal entries are posted
   → Review material stock levels

════════════════════════════════════════════════
Report generated by BuildTrack Report System
════════════════════════════════════════════════`;
}

// ── Fetch all needed data from Firestore ──────────────────────
async function gatherData(uid, projFilter, weekEnd) {
  const endDate   = new Date(weekEnd);
  const startDate = new Date(endDate);
  startDate.setDate(endDate.getDate() - 6);
  const startStr = startDate.toISOString().split("T")[0];

  setStep("Fetching attendance records…");
  const attSnap = await getDocs(query(
    userCol(uid, "attendance"),
    where("date", ">=", startStr),
    where("date", "<=", weekEnd)
  ));
  const att = attSnap.docs.map(d => d.data());

  setStep("Gathering labourer data…");
  const labSnap = await getDocs(userCol(uid, "labourers"));
  const labourers = labSnap.docs.map(d => ({ id: d.id, ...d.data() }));

  setStep("Loading site journal…");
  const logsSnap = await getDocs(query(
    userCol(uid, "daily_logs"),
    where("date", ">=", startStr),
    where("date", "<=", weekEnd)
  ));
  const logs = logsSnap.docs.map(d => d.data())
    .filter(l => !projFilter || l.project === projFilter);

  setStep("Loading expenses…");
  const expSnap = await getDocs(query(
    userCol(uid, "expenses"),
    where("date", ">=", startStr),
    where("date", "<=", weekEnd)
  ));
  const expenses = expSnap.docs.map(d => d.data())
    .filter(e => !projFilter || e.projectName === projFilter || e.project === projFilter);

  setStep("Loading open issues…");
  const issSnap = await getDocs(query(
    userCol(uid, "issues"),
    where("status", "==", "open")
  ));
  const issues = issSnap.docs.map(d => d.data());

  // Compute stats
  const present    = att.filter(a => a.status === "present").length;
  const totalAtt   = att.length;
  const labourCost = labourers.reduce((s, l) => {
    const days = att.filter(a => a.labourerId === l.id && a.status === "present").length;
    return s + days * (l.wagePerDay || 0);
  }, 0);
  const totalExp = expenses.reduce((s, e) => s + (e.amount || 0), 0);
  const pct      = totalAtt ? Math.round(present / totalAtt * 100) : 0;

  return {
    startStr, weekEnd, projFilter,
    logs, labourers, att, expenses, issues,
    present, totalAtt, pct, labourCost, totalExp
  };
}

