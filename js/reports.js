// ── Populate project dropdown ──────────────────────────────────
export function populateWeeklyReportProjects(projects) {
  const sel = document.getElementById("wrProjectSelect");
  if (!sel) return;
  sel.innerHTML = `<option value="">All Projects</option>`;
  projects.forEach(p => {
    sel.innerHTML += `<option value="${p.name}">${p.name}</option>`;
  });
}

// ── Main generate function (global so HTML onclick can call it) ─
window.generateWeeklyReport = async function() {
  const uid = window._uid || window._buildtrackUID;
  if (!uid) return alert("Please log in first.");

  const projFilter = document.getElementById("wrProjectSelect")?.value || "";
  const weekEnd    = document.getElementById("wrWeekEnd")?.value || new Date().toISOString().split("T")[0];

  // Show loading, hide old output
  document.getElementById("wrOutput").style.display = "none";
  document.getElementById("wrStatsRow").style.display = "none";
  document.getElementById("wrLoading").style.display = "flex";
  document.getElementById("wrGenerateBtn").disabled = true;

  try {
    const data = await gatherData(uid, projFilter, weekEnd);

    // Update stats row
    document.getElementById("wrStatAtt").textContent    = data.pct + "%";
    document.getElementById("wrStatLabour").textContent = fmt(data.labourCost);
    document.getElementById("wrStatSpend").textContent  = fmt(data.totalExp);
    document.getElementById("wrStatIssues").textContent = data.issues.length;
    document.getElementById("wrStatsRow").style.display = "grid";

    // Small delay so loading state is visible (mirrors MERN 800ms pause)
    setStep("Writing your report…");
    await new Promise(r => setTimeout(r, 600));

    const text = generateReportText(data);
    window._lastWeeklyReport     = text;
    window._lastWeeklyReportDate = weekEnd;

    document.getElementById("wrContent").textContent = text;
    document.getElementById("wrLoading").style.display = "none";
    document.getElementById("wrOutput").style.display  = "block";

  } catch (err) {
    console.error("[WeeklyReport] Error:", err);
    document.getElementById("wrContent").textContent = "Error generating report: " + err.message;
    document.getElementById("wrLoading").style.display = "none";
    document.getElementById("wrOutput").style.display  = "block";
  } finally {
    document.getElementById("wrGenerateBtn").disabled = false;
  }
};

// ── Copy to clipboard ─────────────────────────────────────────
window.copyWeeklyReport = function() {
  const text = window._lastWeeklyReport || "";
  navigator.clipboard.writeText(text).then(() => {
    const btn = document.querySelector("#wrOutput .btn-secondary");
    if (btn) {
      const orig = btn.textContent;
      btn.textContent = "Copied!";
      setTimeout(() => btn.textContent = orig, 2000);
    }
  });
};

// ── Download as .txt ──────────────────────────────────────────
window.downloadWeeklyReport = function() {
  const text = window._lastWeeklyReport || "";
  const date = window._lastWeeklyReportDate || new Date().toISOString().split("T")[0];
  const blob  = new Blob([text], { type: "text/plain" });
  const url   = URL.createObjectURL(blob);
  const a     = document.createElement("a");
  a.href = url;
  a.download = `BuildTrack_Report_${date}.txt`;
  a.click();
  URL.revokeObjectURL(url);
};

// ── Loading step helper ────────────────────────────────────────
function setStep(text) {
  const el = document.getElementById("wrStep");
  if (el) el.textContent = text;
}
